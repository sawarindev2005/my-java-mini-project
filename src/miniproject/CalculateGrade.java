    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:

        try {
            String studentId = txtStudentID.getText().trim(); //ตัด space หน้า-หลังที่ผู้ใช้อาจกรอกโดยไม่ตั้งใจ
            String name = txtStudentName.getText().trim();
            String surname = txtSurname.getText().trim();
            String midtermText = txtMidterm.getText().trim();
            String finalText = txtFinal.getText().trim();

            // เช็คว่ากรอกครบไหม
            if (studentId.equals("") || name.equals("") || surname.equals("")
                    || midtermText.equals("") || finalText.equals("")) {
                JOptionPane.showMessageDialog(this, "กรุณากรอกข้อมูลให้ครบ");
                return;
            }

            double midterm = Double.parseDouble(midtermText);
            double finals = Double.parseDouble(finalText);

            // เช็คว่าคะแนนอยู่ในช่วงที่ถูกต้อง
            if (midterm < 0 || midterm > 70) {
                JOptionPane.showMessageDialog(this, "คะแนน Midterm ต้องอยู่ระหว่าง 0-70");
                return;
            }
            if (finals < 0 || finals > 30) {
                JOptionPane.showMessageDialog(this, "คะแนน Final ต้องอยู่ระหว่าง 0-30");
                return;
            }

            double total = midterm + finals;
            String grade = calculateGrade(total);

// แสดงค่าใน TextField ก่อน
            txtTotal.setText(String.valueOf(total));
            txtGrade.setText(grade);

            //Chek รหัสนักศึกษาซ้ำ
            String checkSql = "SELECT * FROM student WHERE student_id = '" + studentId + "'";
            if (myDB.selectAllStudents(checkSql).size() > 0) {
                JOptionPane.showMessageDialog(this, "รหัสนักศึกษาซ้ำ กรุณาตรวจสอบอีกครั้ง");
                return;
            }
            // INSERT
            String sql = "INSERT INTO student (student_id, name, surname, midterm, final_score, total, grade) VALUES ('"
                    + studentId + "', '" + name + "', '" + surname + "', "
                    + midterm + ", " + finals + ", " + total + ", '" + grade + "')";

            int row = myDB.stmtCreInsUpdDel(sql);
            if (row > 0) {
                JOptionPane.showMessageDialog(this, "เพิ่มข้อมูลสำเร็จ");

                loadTable();
            } else {
                JOptionPane.showMessageDialog(this, "เพิ่มข้อมูลไม่สำเร็จ");
            }

        } catch (NumberFormatException e) {
            // จับ error กรณีกรอกตัวอักษรในช่องคะแนน
            JOptionPane.showMessageDialog(this, "คะแนนต้องเป็นตัวเลขเท่านั้น");
            System.out.println(e);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "เกิดข้อผิดพลาด: " + e.getMessage());
            System.out.println(e);
        }

    }//GEN-LAST:event_btnAddActionPerformed

