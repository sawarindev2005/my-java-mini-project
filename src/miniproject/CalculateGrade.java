    // ===== ส่วนที่ 1: โหลดตาราง =====
    private void loadTable() {
        model = (DefaultTableModel) tblStudent.getModel();
        model.setRowCount(0);

        ArrayList<StudentInfo> list = myDB.selectAllStudents("SELECT * FROM student");

        // เพิ่มการเช็ค null ตรงนี้
        if (list == null) {
            JOptionPane.showMessageDialog(this, "ไม่สามารถเชื่อมต่อ Database ได้");
            return;
        }

        for (StudentInfo s : list) {
            model.addRow(new Object[]{
                s.getStudentId(),// แสดง student_id ที่ผู้ใช้กรอก
                s.getStudentName(),
                s.getStudentSurname(),
                s.getMidterm(),
                s.getFinalScore(),
                s.getTotal(),
                s.getGrade()
            });
        }
    }

    // ===== ส่วนที่ 2: คำนวณเกรด =====
    private String calculateGrade(double total) {
        if (total >= 80) {
            return "A";
        } else if (total >= 70) {
            return "B";
        } else if (total >= 60) {
            return "C";
        } else if (total >= 50) {
            return "D";
        } else {
            return "E";
        }
    }

