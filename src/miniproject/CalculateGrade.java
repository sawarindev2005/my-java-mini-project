    private void btnSummaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSummaryActionPerformed
        // TODO add your handling code here:
        try {
            Connection conn = myDB.connect();
            Statement stmt = conn.createStatement();

            // -- สรุปจำนวนแต่ละเกรด --
            ResultSet rs1 = stmt.executeQuery(
                    "SELECT grade, COUNT(*) FROM student GROUP BY grade"
            );

            // รีเซ็ตค่าก่อน
            lblCountA.setText("0");
            lblCountB.setText("0");
            lblCountC.setText("0");
            lblCountD.setText("0");
            lblCountE.setText("0");

            int total = 0;

            while (rs1.next()) {
                String g = rs1.getString(1);
                int count = rs1.getInt(2);
                total += count; // รวมทั้งหมด

                if (g.equals("A")) {
                    lblCountA.setText(String.valueOf(count));
                } else if (g.equals("B")) {
                    lblCountB.setText(String.valueOf(count));
                } else if (g.equals("C")) {
                    lblCountC.setText(String.valueOf(count));
                } else if (g.equals("D")) {
                    lblCountD.setText(String.valueOf(count));
                } else if (g.equals("E")) {
                    lblCountE.setText(String.valueOf(count));
                }
            }

            // แสดงจำนวนทั้งหมด
            lblCountTotal.setText(String.valueOf(total));

            // -- สรุปคะแนน max, min, avg --
            ResultSet rs2 = stmt.executeQuery(
                    "SELECT MAX(total), MIN(total), AVG(total) FROM student"
            );
            if (rs2.next()) {
                lblMax.setText(String.format("%.2f", rs2.getDouble(1)));
                lblMin.setText(String.format("%.2f", rs2.getDouble(2)));
                lblAvg.setText(String.format("%.2f", rs2.getDouble(3)));
            }

            conn.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

    }//GEN-LAST:event_btnSummaryActionPerformed

