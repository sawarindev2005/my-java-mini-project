    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        try {
            String saleId = txtSaleID.getText().trim();
            String name = txtSaleName.getText().trim();
            String surname = txtSurname.getText().trim();
            int saleClass = Integer.parseInt(cboSaleClass.getSelectedItem().toString());
            String totalText = txtSaleTotal.getText().trim();

            if (saleId.equals("") || name.equals("") || surname.equals("") || totalText.equals("")) {
                JOptionPane.showMessageDialog(this, "กรุณากรอกข้อมูลให้ครบ");
                return;
            }

            // เช็ค Sale ID ซ้ำ
            String checkSql = "SELECT * FROM sale WHERE sale_id = '" + saleId + "'";
            if (myDB.selectAllSales(checkSql).size() > 0) {
                JOptionPane.showMessageDialog(this, "Sale ID ซ้ำ กรุณาตรวจสอบอีกครั้ง");
                return;
            }

            double saleTotal = Double.parseDouble(totalText);
            double rate = calculateRate(saleClass, saleTotal);

            txtRate.setText(String.valueOf(rate * 100));

            String sql = "INSERT INTO sale (sale_id, name, surname, sale_class, sale_total, rate) VALUES ('"
                    + saleId + "', '" + name + "', '" + surname + "', '"
                    + saleClass + "', " + saleTotal + ", " + rate + ")";

            int row = myDB.stmtCreInsUpdDel(sql);
            if (row > 0) {
                JOptionPane.showMessageDialog(this, "เพิ่มข้อมูลสำเร็จ");
                loadTable();
            } else {
                JOptionPane.showMessageDialog(this, "เพิ่มข้อมูลไม่สำเร็จ");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Sale Total ต้องเป็นตัวเลขเท่านั้น");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "เกิดข้อผิดพลาด: " + e.getMessage());
            System.out.println(e);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void tblSaleMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSaleMouseClicked
        // TODO add your handling code here:
        // 1. หาแถวที่ผู้ใช้เลือก
        int row = tblSale.getSelectedRow();

        // ตรวจสอบกันพลาด ถ้าไม่ได้คลิกเลือกแถวใดเลย row จะเป็น -1
        if (row != -1) {
            try {
                // ดึงข้อมูลจากตาราง (ใช้ .toString() ปลอดภัยกว่าการ Casting ตรงๆ)
                // คอลัมน์ที่ 0, 1, 2... ต้องเรียงตามที่ปรากฏใน JTable บนหน้าจอ

                if (row != -1) {
                    txtSaleID.setText(model.getValueAt(row, 0).toString());
                    txtSaleName.setText(model.getValueAt(row, 1).toString());
                    txtSurname.setText(model.getValueAt(row, 2).toString());
                    cboSaleClass.setSelectedItem(model.getValueAt(row, 3).toString());
                    txtSaleTotal.setText(model.getValueAt(row, 4).toString());
                    txtRate.setText(model.getValueAt(row, 5).toString());
                }

            } catch (Exception e) {
                System.out.println("Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_tblSaleMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        int row = tblSale.getSelectedRow();

        if (row == -1) {
            JOptionPane.showMessageDialog(this, "กรุณาเลือกข้อมูลในตารางก่อน");
            return;
        }

        try {
            // เก็บ sale_id เดิมไว้ใช้ WHERE
            String selectedSaleId = model.getValueAt(row, 0).toString();

            String saleId = txtSaleID.getText().trim();
            String name = txtSaleName.getText().trim();
            String surname = txtSurname.getText().trim();
            int saleClass = Integer.parseInt(cboSaleClass.getSelectedItem().toString());
            String totalText = txtSaleTotal.getText().trim();

            if (saleId.equals("") || name.equals("") || surname.equals("") || totalText.equals("")) {
                JOptionPane.showMessageDialog(this, "กรุณากรอกข้อมูลให้ครบ");
                return;
            }

            double saleTotal = Double.parseDouble(totalText);
            double rate = calculateRate(saleClass, saleTotal);

            // อัปเดต Rate อัตโนมัติ
            txtRate.setText(String.valueOf(rate * 100));

            String sql = "UPDATE sale SET "
                    + "sale_id = '" + saleId + "', "
                    + "name = '" + name + "', "
                    + "surname = '" + surname + "', "
                    + "sale_class = '" + saleClass + "', "
                    + "sale_total = " + saleTotal + ", "
                    + "rate = " + rate
                    + " WHERE sale_id = '" + selectedSaleId + "'";

            int result = myDB.stmtCreInsUpdDel(sql);
            if (result > 0) {
                JOptionPane.showMessageDialog(this, "แก้ไขข้อมูลสำเร็จ");
                loadTable();
            } else {
                JOptionPane.showMessageDialog(this, "แก้ไขข้อมูลไม่สำเร็จ");
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Sale Total ต้องเป็นตัวเลขเท่านั้น");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "เกิดข้อผิดพลาด: " + e.getMessage());
            System.out.println(e);
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int row = tblSale.getSelectedRow();
        try {
            if (row == -1) {
                JOptionPane.showMessageDialog(this, "กรุณาเลือกข้อมูลในตารางก่อน");
                return;
            }

            String selectedSaleId = model.getValueAt(row, 0).toString();
            int confirm = JOptionPane.showConfirmDialog(this, "ยืนยันการลบข้อมูล ID: " + selectedSaleId + " ?");

            if (confirm == JOptionPane.YES_OPTION) {
                int result = myDB.stmtCreInsUpdDel("DELETE FROM sale WHERE sale_id = '" + selectedSaleId + "'");
                if (result > 0) {
                    JOptionPane.showMessageDialog(this, "ลบข้อมูลสำเร็จ");
                    loadTable();
                }
            }
        } catch (Exception e) {
            System.out.println("เกิดข้อผิดพลาด : " + e);
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

