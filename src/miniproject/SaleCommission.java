    private void loadTable() {
        model = (DefaultTableModel) tblSale.getModel();
        model.setRowCount(0);

        ArrayList<SaleInfo> list = myDB.selectAllSales("SELECT * FROM sale");

        if (list == null) {
            JOptionPane.showMessageDialog(this, "ไม่สามารถเชื่อมต่อ Database ได้");
            return;
        }

        for (SaleInfo s : list) {
            model.addRow(new Object[]{
                s.getSaleId(),
                s.getName(),
                s.getSurname(),
                s.getSaleClass(),
                s.getSaleTotal(),
                s.getRate()
            });
        }
    }

    private double calculateRate(int saleClass, double saleTotal) {
        if (saleClass == 1) {
            return saleTotal < 10000 ? 0.01 : 0.02;
        } else if (saleClass == 2) {
            return saleTotal < 10000 ? 0.025 : 0.035;
        } else {
            return saleTotal < 10000 ? 0.04 : 0.05;
        }

    }

